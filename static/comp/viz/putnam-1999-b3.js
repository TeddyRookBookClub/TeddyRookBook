/* Our own diagram for the Putnam solutions guide: lattice points in a cone (1999 B3). */
(window.CompViz = window.CompViz || {})['putnam-1999-b3'] = function (el, api) {
  var W = 640, H = 320, ARIA = 'A grid of lattice points with the cone between the lines n = 2m and m = 2n shaded. Points inside the cone are colored by one of three classes; each class is a shifted copy of the lattice generated by (1,2) and (2,1).';
  'use strict';
  var D = document, NS = 'http://www.w3.org/2000/svg', M = Math;
  el.innerHTML = '';
  var box = D.createElement('div'); box.style.cssText = 'position:relative;max-width:640px;margin:0 auto';
  var svg = D.createElementNS(NS, 'svg'); svg.setAttribute('viewBox', '0 0 ' + W + ' ' + H); svg.setAttribute('width', '100%');
  svg.setAttribute('role', 'img'); svg.style.display = 'block'; svg.setAttribute('aria-label', ARIA);
  var lay = D.createElement('div'); lay.style.cssText = 'position:absolute;inset:0;pointer-events:none;overflow:hidden';
  box.appendChild(svg); box.appendChild(lay); el.appendChild(box);
  var bar = D.createElement('div'); bar.style.cssText = 'display:flex;flex-wrap:wrap;gap:6px;align-items:center;margin-top:8px'; el.appendChild(bar);
  var cap = D.createElement('p'); cap.style.cssText = 'margin:.4em 0 0;font-size:.92em'; cap.setAttribute('aria-live', 'polite'); el.appendChild(cap);
  var labs = {};
  function L(k, x, y, t, col, an) {
    var o = labs[k]; if (!o) { o = labs[k] = { d: D.createElement('div'), t: null }; lay.appendChild(o.d); }
    o.d.style.cssText = 'position:absolute;left:' + (x / W * 100) + '%;top:' + (y / H * 100) + '%;transform:translate(' + (an === 'l' ? '0' : an === 'r' ? '-100%' : '-50%') + ',-50%);white-space:nowrap;font-size:clamp(10px,2.4vw,15px);color:' + col;
    if (o.t !== t) { o.t = t; api.tex(t, o.d); }
  }
  function btn(tt, fn) { var b = D.createElement('button'); b.type = 'button'; b.className = 'cp-btn'; b.textContent = tt; b.addEventListener('click', fn); bar.appendChild(b); return b; }
  function f1(v) { return (+v).toFixed(1); }
  var hl = -1, u = 29, X0 = 35, Y0 = 295, G = 9;
  function draw() {
    var c = api.colors(), pal = [c.blue, c.orange, c.purple], s = '<rect width="' + W + '" height="' + H + '" fill="' + c.panel + '" rx="6"/>', m, n;
    s += '<path d="M' + X0 + ' ' + Y0 + 'L' + (X0 + u * G) + ' ' + (Y0 - u * G / 2) + 'L' + (X0 + u * G) + ' ' + (Y0 - u * G) + 'L' + (X0 + u * G / 2) + ' ' + (Y0 - u * G) + 'Z" fill="' + c.greenSoft + '"/>';
    for (m = 0; m <= G; m++) for (n = 0; n <= G; n++) {
      var x = X0 + u * m, y = Y0 - u * n, inC = 2 * m >= n && 2 * n >= m;
      if (!inC) { s += '<circle cx="' + x + '" cy="' + y + '" r="1.6" fill="' + c.grid + '"/>'; continue; }
      var r = (2 * n - m) % 3, on = hl < 0 || hl === r;
      s += '<circle cx="' + x + '" cy="' + y + '" r="' + (on ? 5 : 3) + '" fill="' + (on ? pal[r] : c.grid) + '"' + (m === 0 && n === 0 ? ' stroke="' + c.ink + '"' : '') + '/>';
    }
    s += '<line x1="' + X0 + '" y1="' + Y0 + '" x2="' + (X0 + u) + '" y2="' + (Y0 - 2 * u) + '" stroke="' + c.red + '" stroke-width="3"/><line x1="' + X0 + '" y1="' + Y0 + '" x2="' + (X0 + 2 * u) + '" y2="' + (Y0 - u) + '" stroke="' + c.red + '" stroke-width="3"/>';
    svg.innerHTML = s;
    L('m', X0 + u * (G + 0.4), Y0, 'm', c.muted, 'l'); L('n', X0, Y0 - u * (G + 0.4), 'n', c.muted, 'c');
    L('g1', X0 + u - 4, Y0 - 2 * u - 12, '(1,2)', c.red, 'r'); L('g2', X0 + 2 * u + 6, Y0 - u + 4, '(2,1)', c.red, 'l');
    L('f1', 330, 40, '(m,n)=a(1,2)+b(2,1)', c.ink, 'l');
    L('f2', 330, 80, '\\qquad +\\,r(1,1),\\ \\ r\\in\\{0,1,2\\}', c.ink, 'l');
    L('f3', 330, 140, '1+S=\\dfrac{1+xy+x^2y^2}{(1-xy^2)(1-x^2y)}', c.ink, 'l');
    L('f4', 330, 205, '(1-xy^2)(1-x^2y)S \\to 3', c.green, 'l');
    cap.textContent = hl < 0 ? 'Lattice points in the cone between the lines n = 2m and m = 2n, colored by the remainder r. Each color is a copy of the grid spanned by (1,2) and (2,1), shifted by r(1,1).' : 'Showing the points with r = ' + hl + ': a copy of the lattice spanned by (1,2) and (2,1), shifted by ' + hl + '·(1,1).';
  }
  btn('All', function () { hl = -1; draw(); });
  [0, 1, 2].forEach(function (r) { btn('r = ' + r, function () { hl = r; draw(); }); });
  api.onTheme(draw); draw();
};
