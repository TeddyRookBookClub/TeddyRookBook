#!/usr/bin/env node
/* Vocabulary Ladder: build the course files from the word data. Run after editing anything in data/vocab/.

   node scripts/vocab/build.js            build everything (prints what changed)
   node scripts/vocab/build.js --check    build in memory only and exit 1 if a built file is out of date

   Reads   data/vocab/list.json            the 1,000-word list (100 topics x 10, strands and levels)
           data/vocab/roots.json           prefixes, roots and suffixes (MathLadder.vocab.ROOTS)
           data/vocab/topics/adv.json      the Advanced Vocabulary skill map (titles, trouble notes)
           data/vocab/words/<topic>.json   one file per adv topic: intro, after, words (10 entries), items, sources
   Writes  static/vocab/viz/vocab.js       only the data block between @@VOCAB-DATA-START@@ and @@VOCAB-DATA-END@@
           static/vocab/gen/adv.js         the word entries (without pictures) and one generator per topic that has a file
           data/vocab/lessons/adv.json     each topic's lesson: intro, the ten word cards, root trees, the trouble note,
                                           the "after" blocks and an inline practice problem
   The roots course (data/vocab/lessons/roots.json, static/vocab/gen/roots.js) is written by hand, not by this script.
   Then run: node scripts/vocab/check-words.js, node scripts/math/check-course.js vocab, node scripts/math/check-gen.js adv */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const D = p => path.join(ROOT, 'data', 'vocab', p);
const CHECK = process.argv.includes('--check');
function read(f) { return JSON.parse(fs.readFileSync(f, 'utf8')); }
const changed = [];
function write(f, s) {
  const old = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
  if (old === s) return;
  changed.push(path.relative(ROOT, f));
  if (!CHECK) { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); }
}

const LIST = read(D('list.json')), ROOTS = read(D('roots.json')).roots, ADV = read(D('topics/adv.json'));
// ---------------------------------------------------------------- 1. the data block in the kit
const tIndex = {}; LIST.topics.forEach((t, i) => { tIndex[t.key] = i; });
const data = {
  strands: LIST.strands.map(s => s.title),
  topics: LIST.topics.map(t => [t.key, t.title, t.strand, t.level]),
  words: LIST.words.map(w => [w.word, w.pos, tIndex[w.topic], w.gloss].concat(w.roots || [])),
  roots: {}
};
Object.keys(ROOTS).forEach(k => { const r = ROOTS[k]; data.roots[k] = [r.form, r.kind, r.means, r.lang, r.topic, r.words || [], r.ex || []]; });
const kitF = path.join(ROOT, 'static/vocab/viz/vocab.js');
if (fs.existsSync(kitF)) {
  const kit = fs.readFileSync(kitF, 'utf8'), a = kit.indexOf('@@VOCAB-DATA-START@@'), b = kit.indexOf('/* @@VOCAB-DATA-END@@');
  if (a < 0 || b < 0) { console.error('static/vocab/viz/vocab.js has no data markers'); process.exit(1); }
  const head = kit.slice(0, kit.indexOf('\n', a) + 1), tail = kit.slice(b);
  write(kitF, head + '  VO.DATA = ' + JSON.stringify(data) + ';\n  ' + tail);
}

// ---------------------------------------------------------------- 2. the word files
const wdir = D('words'), files = fs.existsSync(wdir) ? fs.readdirSync(wdir).filter(f => f.endsWith('.json')).sort() : [];
const topicMeta = {}; ADV.topics.forEach(t => { topicMeta[t.slug] = t; });
const byTopic = {}, items = {}, problems = [];
files.forEach(f => {
  const key = f.replace(/\.json$/, '');
  if (!topicMeta[key]) { problems.push('data/vocab/words/' + f + ': no topic "' + key + '" in topics/adv.json'); return; }
  let T; try { T = read(path.join(wdir, f)); } catch (e) { problems.push('data/vocab/words/' + f + ': ' + e.message); return; }
  if (!Array.isArray(T.words) || !T.words.length) return;
  byTopic[key] = T;
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

// ---------------------------------------------------------------- 3. static/vocab/gen/adv.js
function lean(e) { // what generators need (the pictures stay in the lessons and on the pages)
  const o = { word: e.word, say: e.say, pos: e.pos, def: e.def, ex: e.ex, ctx: e.ctx, syn: e.syn || [], ant: e.ant || [] };
  if (e.family && e.family.length) o.family = e.family.map(f => ({ w: f.w, pos: f.pos })); // the generators' meaning relations use family forms
  if (e.roots && e.roots.length) o.roots = e.roots.map(r => ({ part: r.part, means: r.means }));
  if (e.mn) o.mn = { cue: e.mn.cue, text: e.mn.text };
  return o;
}
const order = ADV.topics.map(t => t.slug).filter(k => byTopic[k]);
const genData = {}, genItems = {};
order.forEach(k => { genData[k] = byTopic[k].words.map(lean); if (byTopic[k].items && byTopic[k].items.length) genItems[k] = byTopic[k].items; });
let gen = '/* Vocabulary Ladder: Advanced Vocabulary generators. GENERATED by scripts/vocab/build.js from data/vocab/words/*.json:\n' +
  '   do not edit this file; edit the word files and run the script. Problems come from MathLadder.vocab.gen.topic (static/vocab/viz/vocab.js). */\n' +
  '(function (W) {\n  \'use strict\';\n  var ML = W.MathLadder = W.MathLadder || {};\n  var DATA = ' + JSON.stringify(genData) + ';\n  var ITEMS = ' + JSON.stringify(genItems) + ';\n' +
  '  (ML.vocabData = ML.vocabData || []).push(DATA);\n  if (ML.vocab && ML.vocab.addEntries) { ML.vocab.addEntries(DATA); ML.vocab.setItems(ITEMS); } else ML.vocabItems = ITEMS;\n' +
  '  var G = ML.gen;\n  function T(id) { return function (R, ctx) { return ML.vocab.gen.topic(id, R, ctx); }; }\n';
order.forEach(k => { gen += "  G('adv." + k + "', T('adv." + k + "'));\n"; });
gen += '})(typeof window !== \'undefined\' ? window : globalThis);\n';
if (order.length) write(path.join(ROOT, 'static/vocab/gen/adv.js'), gen);

// ---------------------------------------------------------------- 4. data/vocab/lessons/adv.json
const WEBSTER = { name: "Webster's Revised Unabridged Dictionary (1913), for word histories", url: 'https://www.gutenberg.org/ebooks/29765' };
const lessons = {};
order.forEach(k => {
  const T = byTopic[k], meta = topicMeta[k], blocks = [];
  (T.intro && T.intro.length ? T.intro : [{ t: 'p', html: meta.short }]).forEach(b => blocks.push(b));
  blocks.push({ t: 'h', text: 'The ten words' });
  T.words.forEach(e => blocks.push({ t: 'viz', name: 'vo-word', opts: { entry: e } }));
  const rootTopics = (meta.prereqs || []).filter(p => p.indexOf('roots.') === 0);
  if (rootTopics.length) {
    const keys = Object.keys(ROOTS).filter(rk => rootTopics.includes(ROOTS[rk].topic) && (ROOTS[rk].words || []).some(w => T.words.some(e => e.word === w)));
    if (keys.length) { blocks.push({ t: 'h', text: 'The roots at work' }); keys.forEach(rk => blocks.push({ t: 'viz', name: 'vo-roots', opts: { root: rk, max: 12 }, cap: 'Words built on ' + ROOTS[rk].form + ' (' + ROOTS[rk].means + ').' })); }
  }
  if (meta.trouble) blocks.push({ t: 'mistake', html: meta.trouble });
  (T.after || []).forEach(b => blocks.push(b));
  blocks.push({ t: 'try' });
  lessons['adv.' + k] = { blocks: blocks, sources: [WEBSTER].concat(T.sources || []) };
});
if (order.length) write(D('lessons/adv.json'), JSON.stringify(lessons, null, 1) + '\n');

console.log((CHECK ? 'checked: ' : 'built: ') + order.length + ' of ' + ADV.topics.length + ' topics have word files' + (changed.length ? '; ' + (CHECK ? 'out of date: ' : 'wrote: ') + changed.join(', ') : '; everything up to date'));
if (CHECK && changed.length) process.exit(1);
