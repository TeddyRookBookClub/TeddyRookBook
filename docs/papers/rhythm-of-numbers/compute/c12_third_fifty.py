def multi_tail(n, pr, test):
    tot = 0.0
    for a in range(n + 1):
        for b in range(n + 1 - a):
            for c in range(n + 1 - a - b):
                d = n - a - b - c
                if test((a, b, c, d)):
                    tot += math.exp(math.lgamma(n + 1) - sum(math.lgamma(x + 1) for x in (a, b, c, d))
                                    + sum(x * math.log(p) for x, p in zip((a, b, c, d), pr)))
    return tot


