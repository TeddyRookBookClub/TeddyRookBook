def cf_terms(x, n):
    """First n terms [a0; a1, ...] of an mpmath real x (caller sets precision)."""
    t = []
    for _ in range(n):
        a = int(mp.floor(x))
        t.append(a)
        f = x - a
        if f == 0:
            break
        x = 1 / f
    return t


def cf_exact(make, n, dps):
    """Terms that are certain: compute x at two precisions and keep the common prefix (at most n)."""
    with mp.workdps(dps):
        a = cf_terms(make(), n + 50)
    with mp.workdps(dps + 200):
        b = cf_terms(make(), n + 50)
    k = 0
    while k < min(len(a), len(b)) and a[k] == b[k]:
        k += 1
    k -= 1  # the last common term may still be uncertain
    if k < n:
        return cf_exact(make, n, int(dps * 1.6))
    return a[:n]


def convergents(terms):
    """Lists p, q of convergents p_n/q_n, n = 0..len-1 (p_{-1}=1, q_{-1}=0)."""
    p0, q0, p1, q1 = 1, 0, terms[0], 1
    P, Q = [p1], [q1]
    for a in terms[1:]:
        p0, p1 = p1, a * p1 + p0
        q0, q1 = q1, a * q1 + q0
        P.append(p1); Q.append(q1)
    return P, Q


def rhythm_word(frac_terms):
    """Standard words of alpha = [0; a1, a2, ...] (the site's construction, Lothaire ch. 2):
    s_{-1} = hit 'x', s_0 = rest '.', s_1 = s_0^(a1-1) s_{-1}, s_n = s_{n-1}^(a_n) s_{n-2}.
    Returns [s_0, s_1, ..., s_k]; len(s_n) = q_n and s_n holds p_n hits."""
    sm1, s0 = 'x', '.'
    s1 = s0 * (frac_terms[0] - 1) + sm1
    levels = [s0, s1]
    for a in frac_terms[1:]:
        levels.append(levels[-1] * a + levels[-2])
    return levels


def floor_word(alpha, n):
    """Characteristic word: beat n (n = 1, 2, ...) is a hit when floor((n+1)alpha) > floor(n alpha).
    Returned as a 0-indexed string (index m = beat m+1)."""
    out = []
    for m in range(1, n + 1):
        out.append('x' if mp.floor((m + 1) * alpha) > mp.floor(m * alpha) else '.')
    return ''.join(out)


_macros = {}


def macro(name, value):
    """Record a TeX macro \\Name for a computed value (value already formatted as TeX)."""
    assert name.isalpha(), name
    _macros[name] = str(value)


def write_macros(fname):
    with open(os.path.join(GEN, fname), 'w') as f:
        f.write('% generated by compute/' + fname.replace('.tex', '.py') + ' -- do not edit\n')
        for k, v in sorted(_macros.items()):
            f.write('\\newcommand{\\%s}{%s}\n' % (k, v))
    _macros.clear()


def save(name, obj):
    with open(os.path.join(OUT, name), 'w') as f:
        json.dump(obj, f, indent=1)


def load(name):
    with open(os.path.join(OUT, name)) as f:
        return json.load(f)


def commas(n):
    return '{:,}'.format(n).replace(',', '{,}')


